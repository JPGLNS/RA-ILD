def sha256sum(path: Path, chunk_size: int = 1024 * 1024) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while True:
            chunk = handle.read(chunk_size)
            if not chunk:
                break
            digest.update(chunk)
    return digest.hexdigest()


def derive_seed(base_seed: int, *parts: int) -> int:
    text = ":".join(str(x) for x in (base_seed, *parts))
    return int.from_bytes(
        hashlib.sha256(text.encode("utf-8")).digest()[:8],
        "little",
    ) % (2**32 - 1)


def ensure_file(path: Path, label: str) -> None:
    if not path.is_file():
        raise FileNotFoundError(f"{label} not found: {path}")


def ensure_no_missing(df: pd.DataFrame, label: str) -> None:
    n = int(df.isna().sum().sum())
    if n:
        cols = df.isna().sum()
        bad = cols[cols > 0].sort_values(ascending=False).head(20)
        raise ValueError(f"{label} has {n} missing values: {bad.to_dict()}")


def read_core_inputs(args: argparse.Namespace):
    base_path = Path(args.base_matrix).expanduser().resolve()
    manifest_path = Path(args.feature_manifest).expanduser().resolve()
    outer_path = Path(args.outer_assignments).expanduser().resolve()
    inner_path = Path(args.inner_assignments).expanduser().resolve()

    for p, label in [
        (base_path, "base matrix"),
        (manifest_path, "feature manifest"),
        (outer_path, "outer assignments"),
        (inner_path, "inner assignments"),
    ]:
        ensure_file(p, label)

    base = pd.read_csv(base_path)
    manifest = pd.read_csv(manifest_path)
    outer = pd.read_csv(outer_path)
    inner = pd.read_csv(inner_path)

    required_base = {
        args.sample_id_col,
        args.label_col,
        args.age_col,
        args.sex_col,
        args.material_col,
        args.aa_clone_number_col,
    }
    missing = required_base - set(base.columns)
    if missing:
        raise ValueError(f"Base matrix missing columns: {sorted(missing)}")
    if base[args.sample_id_col].duplicated().any():
        raise ValueError("Base matrix has duplicated sample IDs.")
    ensure_no_missing(base, "base matrix")

    base[args.sample_id_col] = base[args.sample_id_col].astype(str)
    base[args.label_col] = base[args.label_col].astype(str).str.upper()

    if args.expected_samples > 0 and len(base) != args.expected_samples:
        raise ValueError(
            f"Expected {args.expected_samples} base samples, observed {len(base)}."
        )

    outer_task = outer[outer["outer_repeat"] == args.outer_repeat].copy()
    if len(outer_task) != len(base):
        raise ValueError(
            f"Outer repeat {args.outer_repeat} has {len(outer_task)} rows, "
            f"expected {len(base)}."
        )
    if set(outer_task[args.sample_id_col].astype(str)) != set(
        base[args.sample_id_col]
    ):
        raise ValueError("Outer assignment sample IDs do not match base matrix.")

    outer_train_ids = set(
        outer_task.loc[
            outer_task["outer_fold"] != args.outer_fold,
            args.sample_id_col,
        ].astype(str)
    )
    outer_valid_ids = set(
        outer_task.loc[
            outer_task["outer_fold"] == args.outer_fold,
            args.sample_id_col,
        ].astype(str)
    )
    if outer_train_ids & outer_valid_ids:
        raise ValueError("Outer training and validation IDs overlap.")
    if outer_train_ids | outer_valid_ids != set(base[args.sample_id_col]):
        raise ValueError("Outer task does not cover all base samples.")

    inner_task = inner[
        (inner["outer_repeat"] == args.outer_repeat)
        & (inner["outer_fold"] == args.outer_fold)
    ].copy()
    inner_task[args.sample_id_col] = inner_task[args.sample_id_col].astype(str)

    if set(inner_task[args.sample_id_col]) != outer_train_ids:
        raise ValueError(
            "Inner assignment IDs are not exactly the selected outer-training IDs."
        )
    if inner_task[args.sample_id_col].duplicated().any():
        raise ValueError("Inner assignment contains duplicated sample IDs.")
    if set(inner_task["inner_fold"]) != set(range(1, args.inner_folds + 1)):
        raise ValueError("Inner assignment does not contain all requested folds.")
    if set(inner_task[args.sample_id_col]) & outer_valid_ids:
        raise ValueError("Outer validation samples leaked into inner assignments.")

    base = base.set_index(args.sample_id_col, drop=False)
    outer_train_order = [
        x for x in base.index.tolist() if x in outer_train_ids
    ]
    outer_valid_order = [
        x for x in base.index.tolist() if x in outer_valid_ids
    ]

    return (
        base,
        manifest,
        outer_task,
        inner_task,
        outer_train_order,
        outer_valid_order,
        {
            "base": base_path,
            "manifest": manifest_path,
            "outer": outer_path,
            "inner": inner_path,
        },
    )


def static_tcr_features_from_manifest(
    manifest: pd.DataFrame,
    base: pd.DataFrame,
) -> List[str]:
    required = {
        "feature_name",
        "present_in_train_base",
        "feature_group",
        "feature_role",
        "reference_drop",
    }
    missing = required - set(manifest.columns)
    if missing:
        raise ValueError(f"Feature manifest missing columns: {sorted(missing)}")

    def as_bool(series: pd.Series) -> pd.Series:
        if pd.api.types.is_bool_dtype(series):
            return series
        return series.astype(str).str.lower().isin({"true", "1", "yes"})

    present = as_bool(manifest["present_in_train_base"])
    ref_drop = as_bool(manifest["reference_drop"])

    selected = manifest.loc[
        present
        & manifest["feature_group"].astype(str).str.startswith("tcr_")
        & manifest["feature_role"].astype(str).eq("candidate_predictor")
        & (~ref_drop),
        "feature_name",
    ].astype(str).tolist()

    selected = [x for x in selected if x in base.columns]
    if not selected:
        raise ValueError("No static TCR features were selected from the manifest.")
    if len(selected) != len(set(selected)):
        raise ValueError("Static TCR feature list contains duplicates.")
    return selected


def cache_paths(cache_dir: Path) -> Dict[str, Path]:
    return {
        "presence": cache_dir / "05_train_public_presence.npz",
        "frequency": cache_dir / "05_train_public_frequency.npz",
        "metadata": cache_dir / "05_train_public_sparse_cache.json",
    }


def source_file_signature(
    sample_ids: Sequence[str],
    clone_dir: Path,
    pattern: str,
) -> List[Dict[str, object]]:
    rows = []
    for sample_id in sample_ids:
        path = clone_dir / pattern.format(sample_id=sample_id)
        ensure_file(path, f"clone table for {sample_id}")
        stat = path.stat()
        rows.append({
            "sample_id": sample_id,
            "path": str(path),
            "size": stat.st_size,
            "mtime_ns": stat.st_mtime_ns,
        })
    return rows


def cache_matches(
    metadata_path: Path,
    sample_ids: Sequence[str],
    catalog_path: Path,
    clone_signatures: Sequence[Mapping[str, object]],
) -> bool:
    if not metadata_path.is_file():
        return False
    try:
        meta = json.loads(metadata_path.read_text(encoding="utf-8"))
    except Exception:
        return False
    return (
        meta.get("sample_ids") == list(sample_ids)
        and meta.get("catalog_sha256") == sha256sum(catalog_path)
        and meta.get("clone_files") == list(clone_signatures)
    )


def build_or_load_sparse_cache(
    args: argparse.Namespace,
    base: pd.DataFrame,
) -> Tuple[sparse.csr_matrix, sparse.csr_matrix, Dict[str, object]]:
    catalog_path = Path(args.public_catalog).expanduser().resolve()
    clone_dir = Path(args.clone_table_dir).expanduser().resolve()
    cache_dir = Path(args.cache_dir).expanduser().resolve()
    ensure_file(catalog_path, "public AA catalog")
    if not clone_dir.is_dir():
        raise FileNotFoundError(f"Clone table directory not found: {clone_dir}")
    cache_dir.mkdir(parents=True, exist_ok=True)

    paths = cache_paths(cache_dir)
    sample_ids = base.index.astype(str).tolist()
    clone_signatures = source_file_signature(
        sample_ids, clone_dir, args.clone_file_pattern
    )

    valid_cache = (
        not args.force_rebuild_cache
        and paths["presence"].is_file()
        and paths["frequency"].is_file()
        and cache_matches(
            paths["metadata"],
            sample_ids,
            catalog_path,
            clone_signatures,
        )
    )

    if valid_cache:
        presence = sparse.load_npz(paths["presence"]).tocsr()
        frequency = sparse.load_npz(paths["frequency"]).tocsr()
        meta = json.loads(paths["metadata"].read_text(encoding="utf-8"))
        if presence.shape != frequency.shape:
            raise ValueError("Cached presence/frequency shapes differ.")
        if presence.shape[0] != len(sample_ids):
            raise ValueError("Cached matrix row count differs from base matrix.")
        return presence, frequency, meta

    catalog = pd.read_csv(catalog_path, usecols=[args.sequence_col])
    catalog[args.sequence_col] = catalog[args.sequence_col].astype(str)
    if catalog[args.sequence_col].duplicated().any():
        raise ValueError("Public AA catalog contains duplicated sequences.")
    if (
        args.expected_catalog_size > 0
        and len(catalog) != args.expected_catalog_size
    ):
        raise ValueError(
            f"Expected catalog size {args.expected_catalog_size}, "
            f"observed {len(catalog)}."
        )

    sequence_to_col = {
        seq: i for i, seq in enumerate(catalog[args.sequence_col].tolist())
    }

    row_parts: List[np.ndarray] = []
    col_parts: List[np.ndarray] = []
    freq_parts: List[np.ndarray] = []
    observed_clone_counts: Dict[str, int] = {}

    for row_idx, sample_id in enumerate(sample_ids):
        path = clone_dir / args.clone_file_pattern.format(sample_id=sample_id)
        clone = pd.read_csv(
            path,
            usecols=[args.sequence_col, args.frequency_col],
        )
        if clone[args.sequence_col].duplicated().any():
            raise ValueError(f"{sample_id} clone table has duplicated AA sequences.")
        clone[args.sequence_col] = clone[args.sequence_col].astype(str)
        clone[args.frequency_col] = pd.to_numeric(
            clone[args.frequency_col], errors="raise"
        )
        if (clone[args.frequency_col] < 0).any():
            raise ValueError(f"{sample_id} has negative frequency_norm.")
        observed_clone_counts[sample_id] = len(clone)

        expected_aa = int(round(float(base.loc[sample_id, args.aa_clone_number_col])))
        if expected_aa != len(clone):
            raise ValueError(
                f"{sample_id}: aa_clone_number={expected_aa}, "
                f"01 rows={len(clone)}."
            )

        mapped = clone[args.sequence_col].map(sequence_to_col)
        keep = mapped.notna().to_numpy()
        cols = mapped[keep].astype(np.int64).to_numpy()
        values = clone.loc[keep, args.frequency_col].to_numpy(dtype=np.float64)

        row_parts.append(np.full(len(cols), row_idx, dtype=np.int32))
        col_parts.append(cols)
        freq_parts.append(values)

        if row_idx == 0 or (row_idx + 1) % 20 == 0 or row_idx + 1 == len(sample_ids):
            print(
                f"[sparse cache] processed {row_idx + 1}/{len(sample_ids)} samples"
            )

    rows = np.concatenate(row_parts) if row_parts else np.array([], dtype=np.int32)
    cols = np.concatenate(col_parts) if col_parts else np.array([], dtype=np.int64)
    freq_values = (
        np.concatenate(freq_parts)
        if freq_parts
        else np.array([], dtype=np.float64)
    )

    shape = (len(sample_ids), len(catalog))
    presence = sparse.csr_matrix(
        (np.ones(len(rows), dtype=np.uint8), (rows, cols)),
        shape=shape,
    )
    frequency = sparse.csr_matrix(
        (freq_values, (rows, cols)),
        shape=shape,
    )
    presence.sum_duplicates()
    frequency.sum_duplicates()

    sparse.save_npz(paths["presence"], presence, compressed=True)
    sparse.save_npz(paths["frequency"], frequency, compressed=True)

    meta = {
        "script_version": SCRIPT_VERSION,
        "sample_ids": sample_ids,
        "catalog_path": str(catalog_path),
        "catalog_sha256": sha256sum(catalog_path),
        "catalog_size": len(catalog),
        "matrix_shape": list(shape),
        "presence_nnz": int(presence.nnz),
        "frequency_nnz": int(frequency.nnz),
        "clone_files": clone_signatures,
        "observed_clone_counts": observed_clone_counts,
    }
    paths["metadata"].write_text(
        json.dumps(meta, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return presence, frequency, meta


def effective_threshold(n: int, prevalence: float, minimum: int) -> int:
    return max(minimum, int(math.ceil(prevalence * n)))


def build_public_reference(
    presence: sparse.csr_matrix,
    reference_rows: np.ndarray,
    labels: np.ndarray,
    args: argparse.Namespace,
) -> PublicReference:
    reference_rows = np.asarray(reference_rows, dtype=int)
    ref_labels = labels[reference_rows]
    ra_rows = reference_rows[ref_labels == "RA"]
    ild_rows = reference_rows[ref_labels == "ILD"]

    if len(ra_rows) < args.group_min_count:
        raise ValueError("Too few RA reference samples.")
    if len(ild_rows) < args.group_min_count:
        raise ValueError("Too few ILD reference samples.")

    total_counts = np.asarray(
        presence[reference_rows].sum(axis=0)
    ).ravel()
    ra_counts = np.asarray(presence[ra_rows].sum(axis=0)).ravel()
    ild_counts = np.asarray(presence[ild_rows].sum(axis=0)).ravel()

    global_threshold = effective_threshold(
        len(reference_rows),
        args.global_min_prevalence,
        args.global_min_count,
    )
    ra_threshold = effective_threshold(
        len(ra_rows),
        args.group_min_prevalence,
        args.group_min_count,
    )
    ild_threshold = effective_threshold(
        len(ild_rows),
        args.group_min_prevalence,
        args.group_min_count,
    )

    global_mask = total_counts >= global_threshold
    ra_group = ra_counts >= ra_threshold
    ild_group = ild_counts >= ild_threshold

    ra_prevalence = ra_counts / len(ra_rows)
    ild_prevalence = ild_counts / len(ild_rows)

    ra_specific_mask = (
        ra_group
        & ((ra_prevalence - ild_prevalence) >= args.specific_prevalence_delta)
    )
    ild_specific_mask = (
        ild_group
        & ((ild_prevalence - ra_prevalence) >= args.specific_prevalence_delta)
    )
    shared_mask = (
        ra_group
        & ild_group
        & ~ra_specific_mask
        & ~ild_specific_mask
    )

    return PublicReference(
        global_mask=global_mask,
        ra_specific_mask=ra_specific_mask,
        ild_specific_mask=ild_specific_mask,
        shared_mask=shared_mask,
        n_reference=len(reference_rows),
        n_ra=len(ra_rows),
        n_ild=len(ild_rows),
        global_threshold=global_threshold,
        ra_threshold=ra_threshold,
        ild_threshold=ild_threshold,
    )


